/// A console title sizes its window to its render target (
/// the title: 3840x2160 on a Series X), which can exceed the host's screen.
/// A top-level window larger than the work area is shrunk to fit, keeping
/// its proportions, and centred; what it shows is scaled to it (the swap
/// chain stretches). `VICTORY_WINDOW_MAX=WIDTHxHEIGHT` applies a smaller
/// limit without changing the title's render targets.
fn fit(parent: HWND, x: i32, y: i32, width: i32, height: i32) -> (i32, i32, i32, i32) {
    let mut area = RECT::default();
    // SAFETY: `area` receives the primary monitor's work area.
    let known =
        unsafe { wm::SystemParametersInfoW(wm::SPI_GETWORKAREA, 0, (&raw mut area).cast(), 0) };
    let limit = window_limit();
    let fitted = fit_with_limit(&area, width, height, limit);
    if !parent.is_null() || known == 0 || fitted == (width, height) {
        return (x, y, width, height);
    }
    tracing::info!(width, height, to = ?fitted, ?limit, "title window fitted to the screen");
    let (w, h) = fitted;
    let left = area.left + (area.right - area.left - w) / 2;
    let top = area.top + (area.bottom - area.top - h) / 2;
    (left, top, w, h)
}

fn parse_window_limit(value: &str) -> Option<(i32, i32)> {
    let (width, height) = value.trim().split_once(['x', 'X'])?;
    let (width, height) = (width.trim().parse().ok()?, height.trim().parse().ok()?);
    (width > 0 && height > 0).then_some((width, height))
}

fn window_limit() -> Option<(i32, i32)> {
    static LIMIT: std::sync::OnceLock<Option<(i32, i32)>> = std::sync::OnceLock::new();
    *LIMIT.get_or_init(|| {
        let value = std::env::var_os("VICTORY_WINDOW_MAX")?;
        let parsed = value.to_str().and_then(parse_window_limit);
        if parsed.is_none() {
            tracing::warn!(
                ?value,
                "ignoring invalid VICTORY_WINDOW_MAX; expected positive WIDTHxHEIGHT"
            );
        }
        parsed
    })
}

fn fit_with_limit(
    area: &RECT,
    width: i32,
    height: i32,
    limit: Option<(i32, i32)>,
) -> (i32, i32) {
    let Some((max_width, max_height)) = limit else {
        return fit_into(area, width, height);
    };
    let bounded = RECT {
        left: 0,
        top: 0,
        right: (area.right - area.left).min(max_width),
        bottom: (area.bottom - area.top).min(max_height),
    };
    fit_into(&bounded, width, height)
}

/// `width` x `height` scaled down to fit `area`, or unchanged if it fits
/// (or is `CW_USEDEFAULT`).
fn fit_into(area: &RECT, width: i32, height: i32) -> (i32, i32) {
    let (aw, ah) = (area.right - area.left, area.bottom - area.top);
    if width <= 0 || height <= 0 || aw <= 0 || ah <= 0 || (width <= aw && height <= ah) {
        return (width, height);
    }
    let scale = f64::min(
        f64::from(aw) / f64::from(width),
        f64::from(ah) / f64::from(height),
    );
    (
        (f64::from(width) * scale) as i32,
        (f64::from(height) * scale) as i32,
    )
}

/// Puts our procedure in front of the title's.
fn hook(hwnd: HWND) {
    if hwnd.is_null() {
        return;
    }
    // SAFETY: a window this thread just created. The title's procedure is
    // stored before ours can run.
    unsafe {
        let title = wm::GetWindowLongPtrW(hwnd, wm::GWLP_WNDPROC);
        wm::SetPropW(hwnd, TITLE_PROC, title as *mut c_void);
        wm::SetWindowLongPtrW(hwnd, wm::GWLP_WNDPROC, window_proc as *const () as isize);
    }
}

/// `VICTORY_DISPLAY` (the launcher's "Display"): `fullscreen`, a window
/// without a frame that fills its monitor; `borderless`, without a frame at
/// the picture's size (smaller where the monitor is), centred; anything else,
/// the window as the title made it. Applied to the title's first top-level
/// window it brings to the front (the first it makes is not that one: run
/// soak1 kept its title bar), 3 s after that and again at 10 s: the title
/// gives it its size in its first seconds. (The launcher did this from its own process before,
/// changing another program's window: one of the things antivirus programs
/// count against an unsigned program.)
fn display_later(hwnd: HWND) {
    static FIRST: AtomicBool = AtomicBool::new(true);
    let Ok(mode) = std::env::var("VICTORY_DISPLAY") else { return };
    if !matches!(mode.as_str(), "fullscreen" | "borderless") || !FIRST.swap(false, Ordering::Relaxed) {
        return;
    }
    let at = hwnd as usize;
    let _ = std::thread::Builder::new().name("victory-display".into()).spawn(move || {
        for (wait, front) in [(3, true), (7, false)] {
            std::thread::sleep(Duration::from_secs(wait));
            // SAFETY: plain calls on the title's window; one that is gone
            // is left alone.
            unsafe { apply_display(at as HWND, mode == "fullscreen", front) };
        }
    });
}

unsafe fn apply_display(hwnd: HWND, fill: bool, front: bool) {
    use windows_sys::Win32::Graphics::Gdi::{GetMonitorInfoW, MONITOR_DEFAULTTONEAREST, MONITORINFO, MonitorFromWindow};
    // SAFETY: (the caller's) a window handle, checked first; out
    // structures of the sizes the calls take.
    unsafe {
        if wm::IsWindow(hwnd) == 0 {
            return;
        }
        let mut info: MONITORINFO = std::mem::zeroed();
        info.cbSize = size_of::<MONITORINFO>() as u32;
        if GetMonitorInfoW(MonitorFromWindow(hwnd, MONITOR_DEFAULTTONEAREST), &mut info) == 0 {
            return;
        }
        let m = info.rcMonitor;
        let (aw, ah) = (m.right - m.left, m.bottom - m.top);
        let (w, h) = if fill {
            (aw, ah)
        } else {
            let mut c: RECT = std::mem::zeroed();
            wm::GetClientRect(hwnd, &mut c);
            let (cw, ch) = (f64::from(c.right.max(320)), f64::from(c.bottom.max(180)));
            let fit = (f64::from(aw) / cw).min(f64::from(ah) / ch).min(1.0);
            ((cw * fit) as i32, (ch * fit) as i32)
        };
        wm::SetWindowLongPtrW(hwnd, wm::GWL_STYLE, (wm::WS_POPUP | wm::WS_VISIBLE | wm::WS_CLIPSIBLINGS) as isize);
        wm::SetWindowPos(
            hwnd,
            std::ptr::null_mut(),
            m.left + (aw - w) / 2,
            m.top + (ah - h) / 2,
            w,
            h,
            wm::SWP_FRAMECHANGED | wm::SWP_SHOWWINDOW,
        );
        if front {
            wm::SetForegroundWindow(hwnd);
        }
    }
}

/// `VICTORY_LAUNCHER_KEYS=1` (set by the launcher): F1 and F2 pressed in the
/// title's window are told on standard output (`victory-key F1`), where the
/// launcher reads them, and the launcher may come to the front (its menu).
/// The launcher used to read the keyboard itself, from outside the game: a
/// keylogger's pattern to antivirus programs.
fn tell_launcher(wparam: WPARAM, lparam: LPARAM) -> bool {
    use std::io::Write;
    static ON: std::sync::OnceLock<bool> = std::sync::OnceLock::new();
    let key = match wparam {
        0x70 => "F1",
        0x71 => "F2",
        _ => return false,
    };
    // Held keys repeat: only the first press.
    if lparam & (1 << 30) != 0 || !*ON.get_or_init(|| std::env::var_os("VICTORY_LAUNCHER_KEYS").is_some_and(|v| v == "1")) {
        return false;
    }
    // SAFETY: plain calls: any process may take the front until the next
    // input (the launcher's menu), the cursor is let go.
    unsafe {
        wm::AllowSetForegroundWindow(wm::ASFW_ANY);
        wm::ClipCursor(std::ptr::null());
    }
    let mut out = std::io::stdout().lock();
    let _ = writeln!(out, "victory-key {key}");
    let _ = out.flush();
    true
}

/// The mouse's movement comes to the title's window that is in front as raw
/// input, for the stand-in pad's right stick (`gameinput::controls`); asked
/// again at every activation, so it follows the window that is shown.
fn mouse_input(hwnd: HWND) {
    use windows_sys::Win32::UI::Input::{RAWINPUTDEVICE, RegisterRawInputDevices};
    let device = RAWINPUTDEVICE { usUsagePage: 1, usUsage: 2, dwFlags: 0, hwndTarget: hwnd };
    // SAFETY: one device description of the size given.
    if unsafe { RegisterRawInputDevices(&device, 1, size_of::<RAWINPUTDEVICE>() as u32) } == 0 {
        tracing::warn!("raw mouse input could not be registered: no mouse look");
    }
}

/// Movement of the mouse from a `WM_INPUT` message.
fn raw_mouse(lparam: LPARAM) {
    use windows_sys::Win32::UI::Input::{GetRawInputData, HRAWINPUT, RAWINPUT, RAWINPUTHEADER, RID_INPUT, RIM_TYPEMOUSE};
    // SAFETY: room for one input of the size given; the system fills it.
    unsafe {
        let mut input: RAWINPUT = std::mem::zeroed();
        let mut size = size_of::<RAWINPUT>() as u32;
        let got = GetRawInputData(lparam as HRAWINPUT, RID_INPUT, (&raw mut input).cast(), &mut size, size_of::<RAWINPUTHEADER>() as u32);
        // (0x1: MOUSE_MOVE_ABSOLUTE, a tablet or a remote desktop: left alone.)
        if got != u32::MAX && input.header.dwType == RIM_TYPEMOUSE && input.data.mouse.usFlags & 0x1 == 0 {
            crate::modules::gameinput::mouse_moved(input.data.mouse.lLastX, input.data.mouse.lLastY);
        }
    }
}

/// While the title is in front and the mouse turns the camera: the cursor
/// is kept inside the window's picture (else it leaves the window and a
/// click lands on another program); let go when it is not.
fn keep_cursor(hwnd: HWND, active: bool) {
    use windows_sys::Win32::Graphics::Gdi::ClientToScreen;
    use windows_sys::Win32::Foundation::POINT;
    // SAFETY: plain calls on our window; out structures of their sizes.
    unsafe {
        if !active || !crate::modules::gameinput::controls().mouse {
            wm::ClipCursor(std::ptr::null());
            return;
        }
        let mut c: RECT = std::mem::zeroed();
        wm::GetClientRect(hwnd, &mut c);
        let (mut from, mut to) = (POINT { x: c.left, y: c.top }, POINT { x: c.right, y: c.bottom });
        ClientToScreen(hwnd, &mut from);
        ClientToScreen(hwnd, &mut to);
        let r = RECT { left: from.x, top: from.y, right: to.x, bottom: to.y };
        wm::ClipCursor(&r);
    }
}

extern "system" fn window_proc(
    hwnd: HWND,
    message: u32,
    wparam: WPARAM,
    lparam: LPARAM,
) -> LRESULT {
    if (message == wm::WM_KEYDOWN || message == wm::WM_SYSKEYDOWN) && tell_launcher(wparam, lparam) {
        return 0;
    }
    match message {
        wm::WM_INPUT => raw_mouse(lparam),
        // (The low word: WA_INACTIVE is 0.)
        wm::WM_ACTIVATE => {
            let active = wparam & 0xFFFF != 0;
            if active {
                mouse_input(hwnd);
                display_later(hwnd);
            }
            keep_cursor(hwnd, active);
        }
        wm::WM_SIZE | wm::WM_MOVE => {
            // SAFETY: a plain query.
            let front = unsafe { wm::GetForegroundWindow() } == hwnd;
            keep_cursor(hwnd, front);
        }
        // No cursor over the picture while the mouse turns the camera.
        wm::WM_SETCURSOR if lparam & 0xFFFF == wm::HTCLIENT as isize && crate::modules::gameinput::controls().mouse => {
            // SAFETY: a plain call.
            unsafe { wm::SetCursor(std::ptr::null_mut()) };
            return 1;
        }
        _ => {}
    }
    // A user close (close button, Alt+F4, window or taskbar menu); a
    // console title never sees one, nor a WM_CLOSE from it.
    if message == wm::WM_SYSCOMMAND && wparam & 0xFFF0 == wm::SC_CLOSE as usize {
        end_title("window closed", Box::new(|| {}));
        return 0;
    }
    // Alt or F10 puts a window into menu mode: the system runs a modal menu
    // loop on the thread that owns the window, which is the title's. The
    // title then stops (no frames, no input) until a key ends the loop, and
    // nothing shows it, since the window has no menu bar;
    // the title aborts itself about half a minute later. A console has no window
    // menu. The mouse still opens it from the title bar.
    if message == wm::WM_SYSCOMMAND && wparam & 0xFFF0 == wm::SC_KEYMENU as usize {
        return 0;
    }
    // SAFETY: the procedure `hook` stored, called the way the system would.
    unsafe {
        let title = wm::GetPropW(hwnd, TITLE_PROC);
        if message == wm::WM_NCDESTROY {
            wm::RemovePropW(hwnd, TITLE_PROC);
        }
        let title = std::mem::transmute::<*mut c_void, wm::WNDPROC>(title);
        wm::CallWindowProcW(title, hwnd, message, wparam, lparam)
    }
}

/// Suspends the title as the console does when it ends it, runs `then`
/// (once), then ends the process. Returns at once; later calls do nothing.
pub(crate) fn end_title(why: &'static str, then: Box<dyn FnOnce() + Send>) {
    static ENDING: AtomicBool = AtomicBool::new(false);
    if ENDING.swap(true, Ordering::SeqCst) {
        return;
    }
    let constrain = constrained().clone();
    let suspend = routines().clone();
    tracing::info!(
        constrained = constrain.len(),
        routines = suspend.len(),
        "{why}: suspending the title"
    );
    // Whoever comes first (the routines or the deadline) runs `then`; the
    // other waits for it, so the process never ends halfway through.
    let then = std::sync::Arc::new(Mutex::new(Some(then)));
    let finish = move |how: &str| {
        let mut then = then.lock().unwrap_or_else(|e| e.into_inner());
        tracing::info!("{how}; ending the title");
        if let Some(then) = then.take() {
            then();
        }
        end();
    };
    let late = finish.clone();
    // Not on the calling thread: titles hand the suspend to their window
    // thread and wait for it inside the routine.
    std::thread::spawn(move || {
        constrain_then_suspend(&constrain, &suspend);
        finish("title suspended");
    });
    std::thread::spawn(move || {
        std::thread::sleep(SUSPEND_DEADLINE);
        late("title did not finish suspending in time");
    });
}

/// Runs the constrained-change routines (constrained), then the suspend
/// routines (quiesced), as the console does when it suspends a title.
/// The game's suspend routine waits for a state that only its
/// constrained routine brings about; called alone it never returns.
fn constrain_then_suspend(constrain: &[Registration], suspend: &[Registration]) {
    for &(_, routine, context) in constrain.iter().chain(suspend) {
        routine(1, context as *mut c_void);
    }
}

/// Set in the environment of a relaunched `victory`: an inherited handle
/// of the process it replaces.
const RELAUNCHED_FROM: &str = "VICTORY_RELAUNCHED_FROM";

/// Starts `victory` again with `args` (after the title has suspended); the
/// new process waits until this one has ended.
pub(crate) fn relaunch(args: Vec<std::ffi::OsString>) {
    use windows_sys::Win32::Foundation::{DUPLICATE_SAME_ACCESS, DuplicateHandle, HANDLE};
    let mut me: HANDLE = std::ptr::null_mut();
    // SAFETY: an inheritable duplicate of our own process handle.
    let duplicated = unsafe {
        DuplicateHandle(
            GetCurrentProcess(),
            GetCurrentProcess(),
            GetCurrentProcess(),
            &mut me,
            0,
            1,
            DUPLICATE_SAME_ACCESS,
        )
    } != 0;
    let spawned = std::env::current_exe().and_then(|exe| {
        let mut command = std::process::Command::new(exe);
        command.args(&args);
        if duplicated {
            command.env(RELAUNCHED_FROM, (me as usize).to_string());
        }
        command.spawn()
    });
    match spawned {
        Ok(child) => tracing::info!(pid = child.id(), ?args, "relaunched"),
        Err(e) => tracing::warn!(%e, "relaunch failed; the title just ends"),
    }
}

/// In a relaunched `victory`: waits (30 s at most) for the process it
/// replaces to be gone, so the two never share the title's files.
pub fn wait_for_previous() {
    use windows_sys::Win32::Foundation::{CloseHandle, HANDLE};
    use windows_sys::Win32::System::Threading::WaitForSingleObject;
    let Some(handle) = std::env::var(RELAUNCHED_FROM)
        .ok()
        .and_then(|h| h.parse::<usize>().ok())
    else {
        return;
    };
    // SAFETY: removing our own variable before any other thread reads it.
    unsafe { std::env::remove_var(RELAUNCHED_FROM) };
    let handle = handle as HANDLE;
    // SAFETY: the inherited process handle the previous process gave us.
    unsafe {
        WaitForSingleObject(handle, 30_000);
        CloseHandle(handle);
    }
}

fn end() {
    // Compiled host pipelines kept for the next run.
    #[cfg(windows)]
    victory_gpu::pipeline::save_pipeline_cache();
    // SAFETY: ends this process, as the console ends a suspended title.
    unsafe { TerminateProcess(GetCurrentProcess(), 0) };
}

pub(crate) fn module() -> HleModule {
    HleModule {
        name: "lifecycle",
        dlls: &[
            "api-ms-win-core-psm-appnotify-*",
            "ext-ms-win-rtcore-ntuser-window-*",
        ],
        exports: vec![
            hle_export!(RegisterAppStateChangeNotification),
            hle_export!(UnregisterAppStateChangeNotification),
            hle_export!(RegisterAppConstrainedChangeNotification),
            hle_export!(UnregisterAppConstrainedChangeNotification),
            hle_export!(CreateWindowExW),
            hle_export!(CreateWindowExA),
        ],
    }
}

